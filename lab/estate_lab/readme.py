"""python -m estate_lab.readme: regenerates the dashboard section of README.md and docs/dashboard.svg from reports/."""

from __future__ import annotations

import json
import math

from .world import ROOT

START = "<!-- dashboard:start (generated by `make readme`; do not edit by hand) -->"
END = "<!-- dashboard:end -->"

ADDS = {
    "today": "people: a monthly patch day per client, critical fixes when someone reads about them, any failed probe pages",
    "auto_merge": "a bot merges every update the day it passes CI, majors included, freezes ignored",
    "gated": "fast lane for critical and high fixes, weekly routine updates aged 5 days, majors reviewed on a budget, canary, 6-hour watch, corroborated paging",
    "gated_no_canary": "ablation: no canary and no watch",
    "gated_no_watch": "ablation: canary but no post-rollout watch",
    "gated_no_fast_lane": "ablation: security fixes wait for the weekly run",
    "gated_naive_pager": "ablation: any failed probe pages",
}


def n(v: float) -> str:
    return f"{int(round(v)):,}"


def main() -> None:
    dev = json.loads((ROOT / "reports" / "dev.json").read_text())
    held_path = ROOT / "reports" / "heldout.json"
    held = json.loads(held_path.read_text()) if held_path.exists() else None
    by = {d["design"]: d for d in dev["designs"]}
    today, gated, auto = by["today"], by["gated"], by["auto_merge"]
    cost = {c["method"]: c for c in dev["cost"]}
    est = dev["estimates"]
    L: list[str] = []
    p = L.append

    def maint(d: dict) -> float:
        return d["person_hours_total"] - d["person_hours"].get("major reviews", 0.0)

    p("")
    p("![Results dashboard](docs/dashboard.svg)")
    p("")
    p(f"**Dev estate** (seed {dev['seed']}): {dev['clients']} clients, {dev['apps']} delivered apps "
      f"({', '.join(f'{v} {k}' for k, v in dev['stacks'].items())}), {n(dev['dependencies'])} dependencies on "
      f"{dev['packages']} packages, {n(dev['releases'])} releases ({dev['regressions']} with a regression), "
      f"{dev['advisories']} advisories over {dev['days']} days. Every design saw the same releases, advisories, "
      "outages and probe blips.")
    p("")
    p("| What the agency and its clients see | Today (people) | Gated estate platform |")
    p("|---|---:|---:|")
    p(f"| Critical advisories: p90 days in production after a fix existed | {today['exposure']['critical']['p90_days']} | "
      f"**{gated['exposure']['critical']['p90_days']}** |")
    p(f"| High advisories: app-days in production after a fix existed | {n(today['exposure']['high']['app_days'])} | "
      f"**{n(gated['exposure']['high']['app_days'])}** |")
    p(f"| Critical and high advisories still open at the end | "
      f"{today['exposure']['critical']['open_at_end'] + today['exposure']['high']['open_at_end']} | "
      f"**{gated['exposure']['critical']['open_at_end'] + gated['exposure']['high']['open_at_end']}** |")
    p(f"| Pages to on-call (share that were probe noise) | {n(today['pages'])} ({100 * today['noise_page_share']:.0f}%) | "
      f"**{n(gated['pages'])} ({100 * gated['noise_page_share']:.0f}%)** |")
    p(f"| Broken-deploy minutes per app-month (auto-merge bot: {auto['broken_minutes_per_app_month']:,.0f}) | "
      f"{today['broken_minutes_per_app_month']:.1f} | **{gated['broken_minutes_per_app_month']:.1f}** |")
    p(f"| Person-hours on maintenance and on-call | {n(maint(today))} | **{n(maint(gated))}** |")
    p(f"| Person-hours invested in major upgrades | {n(today['person_hours'].get('major reviews', 0))} | "
      f"**{n(gated['person_hours'].get('major reviews', 0))}** |")
    p(f"| Dependencies a major version behind at the end | {n(today['majors_behind'])} | **{n(gated['majors_behind'])}** |")
    p(f"| Deploys during a client's campaign freeze (auto-merge bot: {auto['deploys_in_freeze']}) | "
      f"{today['deploys_in_freeze']} | **{gated['deploys_in_freeze']}** (critical fixes only) |")
    g = cost["guarded audit"]
    p(f"| Idle cloud spend found per month, of €{n(g['possible_saving_eur'])} findable | €0 | **€{n(g['monthly_saving_eur'])}**, "
      f"{g['wrong_actions']} wrong |")
    p(f"| Project estimates overrun by more than 15% | {100 * est[0]['overrun_share']:.0f}% | **{100 * est[-1]['overrun_share']:.0f}%** |")
    p("")
    p("Today's process breaks nothing in this world because it updates once a month, by which time most bad releases "
      "have been fixed upstream; it pays for that with months of exposure on high advisories, a pager that is 97% noise "
      "and a growing pile of old major versions. The platform's own breakages are the price of patching within a day.")
    p("")
    p("### The designs")
    p("")
    p("| Design | What it does | Critical p90 days | High app-days | Broken deploys | Broken min / app-month | Pages (noise) | Person-hours | Majors behind |")
    p("|---|---|---:|---:|---:|---:|---:|---:|---:|")
    for d in dev["designs"]:
        name = f"**{d['design']}**" if d["design"] == dev["proposed"] else d["design"]
        p(f"| {name} | {ADDS.get(d['design'], '')} | {d['exposure']['critical']['p90_days']} | "
          f"{n(d['exposure']['high']['app_days'])} | {d['broken_deploys']} | {d['broken_minutes_per_app_month']:,.1f} | "
          f"{n(d['pages'])} ({100 * d['noise_page_share']:.0f}%) | {n(d['person_hours_total'])} | {n(d['majors_behind'])} |")
    p("")
    p(f"In the gated design the canary ran {n(gated['canary_runs'])} times and rolled back {gated['canary_true_rollbacks']} "
      f"broken updates ({gated['canary_false_rollbacks']} false alarms); the 6-hour watch caught {gated['watch_rollbacks']} "
      f"more that the canary missed ({gated['watch_false_rollbacks']} false alarms, each an hour of someone's time). "
      f"On an average review day {gated['review_backlog_avg']:.0f} majors wait for the budget of 8 reviews a week.")
    p("")
    p("### Cloud cost across client accounts")
    p("")
    p("| Method | Findings | Saving per month | Would remove something needed | What it would have removed |")
    p("|---|---:|---:|---:|---|")
    for c in dev["cost"]:
        kinds = ", ".join(f"{v} {k}" for k, v in c["wrong_action_kinds"].items()) or "nothing"
        p(f"| {c['method']} | {c['findings']} | €{n(c['monthly_saving_eur'])} | {c['wrong_actions']} | {kinds} |")
    p("")
    p(f"Total spend €{n(g['monthly_eur_total'])} a month over {g['resources']} resources. Seasonal means a campaign site "
      "that is idle now and busy in the same weeks last year; migrating means a volume detached on purpose.")
    p("")
    p("### Estimates from client briefs")
    p("")
    p("| Who estimates | Median error | Overrun > 15% | Fixed-price margin lost | Quoted > 1.6× actual | Asked the client first | Person-hours |")
    p("|---|---:|---:|---:|---:|---:|---:|")
    for e in est:
        p(f"| {e['method']} | {100 * e['median_abs_error']:.0f}% | {100 * e['overrun_share']:.0f}% | €{n(e['margin_lost_eur'])} | "
          f"{100 * e['overquoted_share']:.0f}% | {e['asked_client']} | {n(e['person_hours'])} |")
    p("")
    p(f"{est[0]['briefs']} briefs. The agent quotes its P80 from the agency's own past projects, so it overruns rarely "
      "and over-quotes sometimes; a person approves every draft.")
    p("")
    p("### Release gate (config/estate.json)")
    p("")
    for c in dev["gate"]["checks"]:
        p(f"- {c}")
    p("")
    if held:
        hb = {d["design"]: d for d in held["designs"]}
        ht, hg = hb["today"], hb["gated"]
        p("### Held-out estate (run once)")
        p("")
        p(f"Seed {held['seed']}: other clients, apps and luck, more Python and Node, {held['advisories']} advisories, "
          "more probe blips and outages, and client briefs in phrasings the reader was never written against. "
          "See docs/heldout.md.")
        p("")
        p("| | Dev today | Dev gated | Held-out today | Held-out gated |")
        p("|---|---:|---:|---:|---:|")
        rows = [
            ("Critical p90 days exposed", lambda d: d["exposure"]["critical"]["p90_days"]),
            ("High app-days exposed", lambda d: n(d["exposure"]["high"]["app_days"])),
            ("Broken min / app-month", lambda d: f"{d['broken_minutes_per_app_month']:.1f}"),
            ("Pages (noise share)", lambda d: f"{n(d['pages'])} ({100 * d['noise_page_share']:.0f}%)"),
            ("Person-hours", lambda d: n(d["person_hours_total"])),
        ]
        for label, f in rows:
            p(f"| {label} | {f(today)} | {f(gated)} | {f(ht)} | {f(hg)} |")
        he = held["estimates"]
        p(f"| Estimates overrun > 15% | {100 * est[0]['overrun_share']:.0f}% | {100 * est[-1]['overrun_share']:.0f}% | "
          f"{100 * he[0]['overrun_share']:.0f}% | {100 * he[-1]['overrun_share']:.0f}% |")
        hc = held["cost"][-1]
        p(f"| Cost findings that would remove something needed | 0 | {g['wrong_actions']} | 0 | {hc['wrong_actions']} |")
        p(f"| Gate | | {'pass' if dev['gate']['pass'] else '**fail**'} | | {'pass' if held['gate']['pass'] else '**fail**'} |")
        p("")
        for c in held["gate"]["checks"]:
            if c.startswith("FAIL"):
                p(f"- held-out {c}")
        p("")
    readme = ROOT / "README.md"
    text = readme.read_text()
    i, j = text.index(START), text.index(END)
    readme.write_text(text[: i + len(START)] + "\n".join(L) + "\n" + text[j:])
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "dashboard.svg").write_text(svg(dev, held))


def svg(dev: dict, held: dict | None) -> str:
    ink, muted, rule, good, bad, paper = "#17212b", "#5b6773", "#d8dee4", "#0e6e55", "#b2502a", "#ffffff"
    by = {d["design"]: d for d in dev["designs"]}
    today, gated = by["today"], by["gated"]
    g = next(c for c in dev["cost"] if c["method"] == "guarded audit")
    W = 960
    rows = dev["designs"]
    H = 230 + len(rows) * 32 + 90
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" '
         'font-family="-apple-system, \'Segoe UI\', Helvetica, Arial, sans-serif">',
         f'<rect width="100%" height="100%" fill="{paper}"/>',
         f'<text x="32" y="40" font-size="20" font-weight="600" fill="{ink}">An agency estate of {dev["apps"]} client apps over '
         f'{dev["days"]} days</text>',
         f'<text x="32" y="62" font-size="13" fill="{muted}">{dev["advisories"]} advisories, {n(dev["releases"])} releases, the same '
         'luck for every design; dev world, seed ' + str(dev["seed"]) + '</text>']
    tiles = [
        (f"{gated['exposure']['critical']['p90_days']} d", f"{today['exposure']['critical']['p90_days']} d today",
         "critical fix in production, p90"),
        (n(gated["pages"]), f"{n(today['pages'])} today", "pages to on-call"),
        (f"€{n(g['monthly_saving_eur'])}", "€0 today", "idle cloud spend found / month"),
        (f"{100 * dev['estimates'][-1]['overrun_share']:.0f}%", f"{100 * dev['estimates'][0]['overrun_share']:.0f}% today",
         "estimates overrun > 15%"),
    ]
    tw = (W - 64 - 3 * 16) // 4
    for i, (big, was, label) in enumerate(tiles):
        x = 32 + i * (tw + 16)
        o.append(f'<rect x="{x}" y="84" width="{tw}" height="96" rx="6" fill="none" stroke="{rule}"/>')
        o.append(f'<text x="{x + 16}" y="126" font-size="27" font-weight="700" fill="{good}">{big}</text>')
        o.append(f'<text x="{x + tw - 14}" y="126" font-size="13" fill="{bad}" text-anchor="end">{was}</text>')
        o.append(f'<text x="{x + 16}" y="158" font-size="13" fill="{muted}">{label}</text>')
    top = 216
    o.append(f'<text x="32" y="{top}" font-size="14" font-weight="600" fill="{ink}">App-days running a high-severity flaw after its '
             'fix was out (log scale)</text>')
    vals = [max(1.0, d["exposure"]["high"]["app_days"]) for d in rows]
    hi = math.log10(max(vals) * 1.3)
    x0, x1 = 230.0, W - 120.0
    for i, d in enumerate(rows):
        y = top + 16 + i * 32
        v = max(1.0, d["exposure"]["high"]["app_days"])
        w = (math.log10(v) / hi) * (x1 - x0)
        col = good if d["design"] == dev["proposed"] else (bad if d["design"] == "today" else muted)
        weight = "700" if d["design"] == dev["proposed"] else "400"
        o.append(f'<text x="32" y="{y + 15}" font-size="13" font-weight="{weight}" fill="{ink}">{d["design"]}</text>')
        o.append(f'<rect x="{x0}" y="{y + 2}" width="{w:.1f}" height="18" rx="3" fill="{col}"/>')
        o.append(f'<text x="{x0 + w + 8:.1f}" y="{y + 16}" font-size="13" fill="{ink}">{n(d["exposure"]["high"]["app_days"])}</text>')
    foot = top + 16 + len(rows) * 32 + 30
    o.append(f'<line x1="32" x2="{W - 32}" y1="{foot - 18}" y2="{foot - 18}" stroke="{rule}"/>')
    notes = [f"Broken-deploy minutes per app-month: gated {gated['broken_minutes_per_app_month']:.1f}, today "
             f"{today['broken_minutes_per_app_month']:.1f}, auto-merge {by['auto_merge']['broken_minutes_per_app_month']:,.0f}."]
    if held:
        hg = next(d for d in held["designs"] if d["design"] == "gated")
        notes.append(f"Held-out estate (seed {held['seed']}, run once): gated critical p90 {hg['exposure']['critical']['p90_days']} days, "
                     f"{n(hg['pages'])} pages, gate {'passed' if held['gate']['pass'] else 'failed'}.")
    notes.append("Simulated estate; see Limits in the README.")
    for i, t in enumerate(notes):
        o.append(f'<text x="32" y="{foot + i * 18}" font-size="12" fill="{muted}">{t}</text>')
    o.append("</svg>")
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    main()
